-- H22 (SCRUM-133): registro de señales declaradas por usuario. El perfil guarda hechos, nunca puntajes (ADR-004).
-- Quitar = desactivar; deshacer = reactivar. No se registran impresiones, aperturas ni analítica.
-- Migración aditiva (ADR-005): preferencias_usuario se conserva y la API la sigue escribiendo (ADR-009).

create table public.senales_usuario (
  -- by default: la restauración de respaldos inserta el id de la foto.
  id bigint generated by default as identity primary key,
  usuario_id text not null references public.perfiles(id) on delete cascade,
  clase text not null,
  ambito text not null,
  valor text not null check (char_length(btrim(valor)) between 1 and 100),
  origen text not null check (origen in ('encuesta', 'pregunta', 'tarjeta')),
  activa boolean not null default true,
  creada_en timestamptz not null default now(),
  actualizada_en timestamptz not null default now(),
  constraint senales_usuario_clase_ambito check (
    (clase = 'interes' and ambito in ('categoria', 'subcategoria', 'comercio'))
    or (clase = 'criterio' and ambito in ('canal', 'beneficio', 'descubrir', 'zona'))
    or (clase = 'rechazo' and ambito in ('oferta', 'comercio', 'categoria'))
  ),
  constraint senales_usuario_unica unique (usuario_id, clase, ambito, valor)
);

-- El motor solo lee las señales activas de un usuario: el índice parcial cubre esa consulta.
create index senales_usuario_activas_idx on public.senales_usuario (usuario_id) where activa;

-- Igual que el resto de tablas protegidas: el navegador nunca accede; solo el backend con service_role.
alter table public.senales_usuario enable row level security;
revoke all on table public.senales_usuario from public, anon, authenticated;
grant select, insert, update, delete on table public.senales_usuario to service_role;

-- Las categorías ya elegidas pasan al registro como interés·categoría con origen encuesta.
insert into public.senales_usuario (usuario_id, clase, ambito, valor, origen)
select preferencia.usuario_id, 'interes', 'categoria', categoria, 'encuesta'
from public.preferencias_usuario as preferencia
cross join lateral unnest(preferencia.categorias) as categoria
on conflict (usuario_id, clase, ambito, valor) do nothing;
